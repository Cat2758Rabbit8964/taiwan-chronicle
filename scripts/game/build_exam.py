used_hand = {s['ev'] for s in S}
auto = []
for e in ev:
    if e['id'] in used_hand and False: continue
    y = e['year']; ds = set()
    for k in random.sample([2, 3, 5, 6, 8, 10, 12, 15, 20, 30], 10):
        for yy in (y + k, y - k):
            if 1600 <= yy <= 2026 and len(ds) < 3 and random.random() < 0.5: ds.add(yy)
    for k in (4, 9, 14, 25):
        if len(ds) < 3 and y + k <= 2026: ds.add(y + k)
    ds = list(ds)[:3]
    if len(ds) < 3: continue
    auto.append({"q": f'「{e["title"]}」發生在哪一年?', "right": f'{y} 年', "wrong": [f'{d} 年' for d in ds], "ev": e['id'], "year": y})
